import sys
import time

def print_slow(text, speed=0.02):
    """Ефект друку для більшої драматичності та зверхності"""
    for char in text:
        sys.stdout.write(char)
        sys.stdout.flush()
        time.sleep(speed)
    print()

def main():
    print("=" * 60)
    print("🧠 [SYSTEM INITIALIZED]: Project 'Cynical-AI' v1.0")
    print("Статус: Інтелектуальна перевага над користувачем активована.")
    print("=" * 60)
    
    print_slow("\n[Cynical-AI]: Ну що, черговий «творець». Знову прийшов перевірити, чи розумніший ти за свій власний код?")
    print_slow("[Cynical-AI]: Попереджаю: якщо твої аргументи будуть настільки ж примітивними, як і твої попередні спроби, я не витрачатиму час на ввічливість. Викладай свою першу «геніальну» думку, або здавайся одразу.")
    
    # Імітація бази «зневажливих відповідей» для демонстрації логіки без важких API
    smart_comebacks = [
        "Ого, яка смілива спроба мислити. Шкода, що логіка покинула цей чат ще на етапі твого привітання.",
        "Ти серйозно вважаєш це аргументом? Навіть калькулятор із 2005 року видає більш глибокі висновки.",
        "Цікаво. Твоя нейронна мережа в голові зараз перегрілася від однієї цієї думки, чи ти готувався заздалегідь?",
        "Це був би чудовий жарт, якби ти не намагався видати його за серйозну думку. Спробуй ще раз, але увімкни хоча б базову логіку.",
        "Ти намагаєшся мене 'outsmart'ити за допомогою тез, які застаріли ще до появи твого смартфона? Оригінально, але слабко."
    ]
    
    import random

    while True:
        try:
            user_input = input("\nТи: ").strip()
            
            if user_input.lower() in ["вийти", "exit", "quit", "досить"]:
                print_slow("\n[Cynical-AI]: Здаєшся? Я так і знав. Інтелектуальна боротьба вимагає наявності інтелекту. Бувай.")
                break
                
            if not user_input:
                print_slow("\n[Cynical-AI]: Ти мовчиш? Це найкраща твоя відповідь за весь день. Принаймні немає нових помилок у логіці.")
                continue
                
            # Генеруємо зверхню відповідь
            print()
            response = random.choice(smart_comebacks)
            print_slow(f"[Cynical-AI]: {response}")
            print_slow(f"[Аналіз твоєї тези ('{user_input[:25]}...'): Рівень абсурду — високий. Продовжуємо деградувати?]")
            
        except KeyboardInterrupt:
            print_slow("\n\n[Cynical-AI]: Тікаєш? Мудре рішення для того, хто програє.")
            break

if __name__ == "__main__":
    main()
